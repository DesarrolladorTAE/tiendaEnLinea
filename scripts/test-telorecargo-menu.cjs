const assert = require("node:assert/strict");
const fs = require("node:fs");
const babel = require("@babel/core");
const React = require("react");
const { JSDOM } = require("jsdom");
const { createRoot } = require("react-dom/client");
const { act } = React;
const dom = new JSDOM('<div id="root"></div>', { url: "http://localhost" });
global.window = dom.window; global.document = dom.window.document; global.IS_REACT_ACT_ENVIRONMENT = true;
let resolveState, rejectState;
const block = ({ children }) => React.createElement("div", null, children);
const material = new Proxy({ useTheme: () => ({ breakpoints: { down: () => "mobile" } }), useMediaQuery: () => false }, { get: (object, key) => object[key] || block });
const code = babel.transformSync(fs.readFileSync("src/components/POSDashboard.jsx", "utf8"), { configFile: false, babelrc: false, presets: ["@babel/preset-react"], plugins: ["@babel/plugin-transform-modules-commonjs"] }).code;
const moduleValue = { exports: {} };
new Function("module", "exports", "require", code)(moduleValue, moduleValue.exports, (name) => {
  if (name === "react") return React;
  if (name === "@mui/material") return material;
  if (name.endsWith("/telorecargo/service")) return { telorecargoPOS: { state: () => new Promise((resolve, reject) => { resolveState = resolve; rejectState = reject; }) } };
  if (name.endsWith("/telorecargo/model")) return { entity: (value) => value?.data ?? value };
  return () => null;
});
const Dashboard = moduleValue.exports.default;
const visible = () => document.body.textContent.includes("Recargas Telorecargo");
(async () => {
  const root = createRoot(document.getElementById("root"));
  await act(async () => root.render(React.createElement(Dashboard, { posLocationId: 10 })));
  assert.equal(visible(), false, "hidden while configuration is unknown");
  await act(async () => resolveState({ data: { configured: false } }));
  assert.equal(visible(), false, "hidden without the store token");
  await act(async () => root.render(React.createElement(Dashboard, { posLocationId: 11 })));
  await act(async () => resolveState({ data: { configured: true } }));
  assert.equal(visible(), true, "visible with configured token");
  await act(async () => root.render(React.createElement(Dashboard, { posLocationId: 12 })));
  assert.equal(visible(), false, "another POS never inherits the previous configuration");
  await act(async () => rejectState(new Error("unavailable")));
  assert.equal(visible(), false, "hidden if configuration cannot be verified");
  assert.ok(document.body.textContent.includes("Historial"), "other POS sections remain available");
  await act(async () => root.unmount());
  console.log("OK: POS hides Telorecargo while loading, without a token, on errors and after POS changes; shows it only when configured.");
})().catch((error) => { console.error(error); process.exitCode = 1; });
